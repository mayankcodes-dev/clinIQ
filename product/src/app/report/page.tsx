type ReportStatus = "loading" | "ready" | "empty" | "error";

function readObject(key: string): Record<string, unknown> {
  try {
    const raw = sessionStorage.getItem(key);
    const value = raw ? JSON.parse(raw) : {};
    return value && typeof value === "object" && !Array.isArray(value)
      ? (value as Record<string, unknown>)
      : {};
  } catch {
    return {};
  }
}

function readDocuments(): Array<Record<string, unknown>> {
  try {
    const raw = sessionStorage.getItem("mk_docs");
    const value = raw ? JSON.parse(raw) : [];
    return Array.isArray(value)
      ? value.filter(
          (document): document is Record<string, unknown> =>
            Boolean(document) && typeof document === "object"
        )
      : [];
  } catch {
    return [];
  }
}

function textValue(value: unknown, fallback = "Not reported"): string {
  if (typeof value === "string" && value.trim()) return value.trim();
  if (typeof value === "number") return String(value);
  return fallback;
}

function listValue(value: unknown): string[] {
  if (!Array.isArray(value)) {
    const text = textValue(value, "");
    return text ? [text] : [];
  }
  return value.map((item) => textValue(item, "")).filter(Boolean);
}

function patientAge(patient: Record<string, unknown>): string {
  const directAge = patient.age ?? patient.patientAge;
  if (directAge !== undefined && directAge !== null && String(directAge).trim()) {
    return String(directAge);
  }
  const yearOfBirth = Number(patient.yearOfBirth);
  if (Number.isFinite(yearOfBirth) && yearOfBirth > 0) {
    return String(new Date().getFullYear() - yearOfBirth);
  }
  return "Not provided";
}

function buildShareText(report: ClinIQClinicalReport, name: string, age: string, gender: string, language: string): string {
  const lines = [
    `*ClinIQ — History & Physical*`,
    `Patient: ${name} | Age: ${age} | Sex: ${gender}`,
    `Date: ${new Date().toLocaleDateString("en-IN")} | Language: ${language.toUpperCase()}`,
    ``,
    `*CHIEF COMPLAINT*`,
    report.chiefComplaint,
    ``,
    `*HISTORY OF PRESENT ILLNESS*`,
    report.historyOfPresentIllness,
    ``,
    `*PAST MEDICAL HISTORY*`,
    report.pastMedicalHistory,
    ``,
    `*MEDICATIONS*`,
    listValue(report.medications).join(", ") || "None reported",
    ``,
    `*ALLERGIES*`,
    listValue(report.allergies).join(", ") || "NKDA",
    ``,
    `*FAMILY & SOCIAL HISTORY*`,
    report.familyAndSocialHistory,
    ``,
    `*REVIEW OF SYSTEMS*`,
    report.reviewOfSystems,
  ];

  if (listValue(report.redFlags).length > 0) {
    lines.push(``, `*[RED FLAGS]*`, listValue(report.redFlags).join("; "));
  }

  if (listValue(report.differentialConsiderations).length > 0) {
    lines.push(``, `*DIFFERENTIAL CONSIDERATIONS*`, listValue(report.differentialConsiderations).join("; "));
  }

  lines.push(``, `_Generated by ClinIQ AI. For physician review only._`);
  return lines.filter((l) => l !== undefined).join("\n");
}

